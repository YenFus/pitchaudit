function fromCopy(
  id: string,
  severity: Issue["severity"],
  finding: string,
  evidence: string[],
  copyId = id
): Issue {
  const copy =
    IMPACT_COPY[copyId] ?? psiFallbackCopy(copyId, "");
  const raw: RawIssue = { id, severity, finding, evidence };
  return {
    id,
    category: copy.category,
    severity,
    title: copy.title,
    finding,
    impact: copy.impact,
    fix: copy.fix,
    evidence,
    pitch: copy.pitch?.(raw) || undefined,
  };
}

